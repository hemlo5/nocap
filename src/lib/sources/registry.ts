function parseCsv(value: string | undefined): string[] {
  if (!value) {
    return [];
  }

  return value
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);
}

function fromEnv(provider: SourceProvider, envName: string): SourceConfig[] {
  return parseCsv(process.env[envName]).map((key) => ({
    provider,
    key,
    id: `${provider}:${key}`,
    type: "ats",
    enabled: true,
    priority: 50,
  }));
}

export function getSourceConfigs(): SourceConfig[] {
  const includeDefaults =
    process.env.NEARHIRE_DISABLE_DEFAULT_SOURCES !== "true";
  const defaults = includeDefaults
    ? companySources.map((source) => ({
        ...source,
        enabled: source.enabled ?? true,
      }))
    : [];

  return [
    ...defaults,
    ...fromEnv("greenhouse", "NEARHIRE_GREENHOUSE_BOARDS"),
    ...fromEnv("lever", "NEARHIRE_LEVER_COMPANIES"),
    ...fromEnv("ashby", "NEARHIRE_ASHBY_BOARDS"),
    ...fromEnv("smartrecruiters", "NEARHIRE_SMARTRECRUITERS_COMPANIES"),
    ...fromEnv("workable", "NEARHIRE_WORKABLE_ACCOUNTS"),
    ...fromEnv("recruitee", "NEARHIRE_RECRUITEE_COMPANIES"),
    ...fromEnv("personio", "NEARHIRE_PERSONIO_COMPANIES"),
    ...fromEnv("bamboohr", "NEARHIRE_BAMBOOHR_COMPANIES"),
    ...fromEnv("breezy", "NEARHIRE_BREEZY_COMPANIES"),
  ].sort((a, b) => (b.priority ?? 0) - (a.priority ?? 0));
}

export function getSourceConfigsForSearch(
  query?: NearbyJobsQuery,
): SourceConfig[] {
  const sources = getSourceConfigs()
    .filter((source) => source.enabled)
    .filter(
      (source) =>
        !query?.sourceProvider ||
        query.sourceProvider === "all" ||
        source.provider === query.sourceProvider,
    );
  if (!query || isLikelyIndiaSearch(query)) {
    return sources.slice(0, maxSourcesPerRequest());
  }

  return sources
    .filter(
      (source) =>
        !source.countries?.length || source.countries.includes("India"),
    )
    .slice(0, maxSourcesPerRequest());
}

export function findSourceConfig(
  provider: string,
  key: string,
): SourceConfig | null {
  return (
    getSourceConfigs().find(
      (source) => source.provider === provider && source.key === key,
    ) ?? null
  );
}

function isLikelyIndiaSearch(query: NearbyJobsQuery): boolean {
  return (
    query.lat >= 6 && query.lat <= 38 && query.lng >= 68 && query.lng <= 98
  );
}

function maxSourcesPerRequest(): number {
  const parsed = Number.parseInt(
    process.env.NEARHIRE_MAX_SOURCES_PER_REQUEST ?? "",
    10,
  );
  return Number.isFinite(parsed) && parsed > 0 ? parsed : 150;
}
